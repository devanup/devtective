export function convertUserStatsToLanguages(
	userStats: UserStats | null,
	username: string,
): Language[] {
	if (!userStats || !userStats[username]) {
		return [];
	}

	const languageStats = userStats[username];
	const totalBytes = Object.values(languageStats).reduce(
		(sum, bytes) => sum + bytes,
		0,
	);

	// Convert to Language array format
	const languages: Language[] = Object.entries(languageStats)
		.map(([name, bytes]) => ({
			label: name,
			value: Math.round((bytes / totalBytes) * 100), // Convert to percentage
			color: LANGUAGE_COLORS[name] || '#808080', // Default gray for unknown languages
		}))
		.sort((a, b) => b.value - a.value) // Sort by percentage descending
		.slice(0, 10); // Take top 10 languages

	// If there are more than 10 languages, group the rest as "Others"
	if (Object.keys(languageStats).length > 10) {
		const othersPercentage = languages
			.slice(9)
			.reduce((sum, lang) => sum + lang.value, 0);
		if (othersPercentage > 0) {
			languages.splice(9); // Remove languages beyond top 9
			languages.push({
				label: 'Others',
				value: othersPercentage,
				color: '#808080',
			});
		}
	}

	return languages;
}
